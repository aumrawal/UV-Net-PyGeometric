"""
Kaggle kernel 2 of 2 (GPU, internet on): train and test UV-Net (PyG) on Fusion 360 Gallery segmentation.

Reads the packed caches written by the preprocessing kernel (attached as a kernel source) and
runs train.py unchanged. Everything under /kaggle/working/results is kept as kernel output:
best.pt, last.pt, epoch_NNN.pt every 10 epochs, TensorBoard events, train.log and test metrics.
Generated by kaggle/build_kernels.py; the project source is embedded below.
"""
import base64
import io
import pathlib
import shutil
import subprocess
import sys
import tarfile
import time

SOURCE_B64 = "__SOURCE_B64__"
EPOCHS = __EPOCHS__
EXPERIMENT = "__EXPERIMENT__"

SRC = pathlib.Path("/tmp/src")
RESULTS = pathlib.Path("/kaggle/working/results")
T0 = time.time()


def sh(cmd, cwd=None, log=None):
    """Run a command, echoing its output (and appending it to `log`)."""
    print(f"\n[{time.time() - T0:6.0f}s] $ {cmd}", flush=True)
    proc = subprocess.Popen(cmd, shell=True, cwd=cwd, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
    with open(log, "a") if log else open("/dev/null", "w") as f:
        for line in proc.stdout:
            print(line, end="", flush=True)
            f.write(line)
            f.flush()
    if proc.wait() != 0:
        sys.exit(f"Command failed with exit code {proc.returncode}: {cmd}")


tarfile.open(fileobj=io.BytesIO(base64.b64decode(SOURCE_B64))).extractall(SRC)
sh("pip install -q torch_geometric==2.8.0.post1")
sh("nvidia-smi --query-gpu=name,memory.total --format=csv")
# Fail in the first minute, not after a CPU-speed epoch, if this image's PyTorch cannot drive the GPU
sh("python -c \"import torch, torch_geometric as g; print('torch', torch.__version__, '| pyg', g.__version__); "
   "x = torch.randn(64, 7, 10, 10, device='cuda'); print(torch.nn.Conv2d(7, 8, 3).cuda()(x).sum().item())\"")

splits = sorted(pathlib.Path("/kaggle/input").rglob("fusion360_processed/split.json"))
assert splits, "fusion360_processed not found under /kaggle/input; is the preprocessing kernel attached?"
data_dir = splits[0].parent
print("Data:", data_dir)

RESULTS.mkdir(parents=True, exist_ok=True)
log = RESULTS / "train.log"
common = f"--dataset fusion360 --data_dir {data_dir} --batch_size 64"
sh(f"python -u train.py train {common} --epochs {EPOCHS} --save_every 10 "
   f"--results_dir {RESULTS} --experiment_name {EXPERIMENT}", cwd=SRC, log=log)

run_dir = sorted((RESULTS / EXPERIMENT).iterdir())[-1]
for name in ("best", "last"):
    sh(f"python -u train.py test {common} --checkpoint {run_dir / (name + '.pt')}", cwd=SRC, log=log)
    shutil.move(run_dir / "test_metrics.json", run_dir / f"test_metrics_{name}.json")
sh(f"ls -la {run_dir}")
print(f"Done in {(time.time() - T0) / 60:.1f} min")
