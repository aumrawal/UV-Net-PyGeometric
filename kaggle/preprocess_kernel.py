"""
Kaggle kernel 1 of 2 (CPU, internet on): Fusion 360 Gallery segmentation s2.0.0 -> packed PyG caches.

Downloads the official zip from Autodesk's bucket, converts the STEP files with
process/fusion360_to_pyg.py inside a micromamba env (pythonocc is not pip-installable), and
leaves split.json and cache/<split>.pt in /kaggle/working/fusion360_processed for the
training kernel. Generated by kaggle/build_kernels.py; the project source is embedded below.
"""
import base64
import io
import json
import os
import pathlib
import shutil
import subprocess
import tarfile
import time

SOURCE_B64 = "__SOURCE_B64__"
LIMIT = __LIMIT__  # models per split; None for the full dataset

URL = "https://fusion-360-gallery-dataset.s3.us-west-2.amazonaws.com/segmentation/s2.0.0/s2.0.0.zip"
SRC = pathlib.Path("/tmp/src")
RAW = pathlib.Path("/tmp/f360")
PROC = pathlib.Path("/tmp/proc")
OUT = pathlib.Path("/kaggle/working/fusion360_processed")
ENV = "/tmp/occ"
T0 = time.time()


def sh(cmd, cwd=None):
    print(f"\n[{time.time() - T0:6.0f}s] $ {cmd}", flush=True)
    subprocess.run(cmd, shell=True, check=True, cwd=cwd)


tarfile.open(fileobj=io.BytesIO(base64.b64decode(SOURCE_B64))).extractall(SRC)

# Same package versions as environment.yml, with the CPU build of PyTorch
sh("curl -Ls https://micro.mamba.pm/api/micromamba/linux-64/latest | tar -xj -C /tmp bin/micromamba")
sh(f"/tmp/bin/micromamba create -y -q -p {ENV} -c conda-forge python=3.11 pythonocc-core=7.7.2 "
   f"'pytorch=2.*=cpu*' numpy=1.26 scipy tqdm networkx pip")
sh(f"{ENV}/bin/pip install -q torch_geometric==2.8.0.post1 deprecate")
sh(f"{ENV}/bin/pip install -q --no-deps git+https://github.com/AutodeskAILab/occwl.git")
sh(f"{ENV}/bin/python -c \"import torch, torch_geometric, OCC, occwl.graph, occwl.uvgrid; "
   f"print('torch', torch.__version__, '| pyg', torch_geometric.__version__, '| occ', OCC.VERSION)\"")

# Only the B-reps and labels are needed; meshes and point clouds make up most of the archive
sh(f"curl -L --fail --retry 5 -sS -o /tmp/s2.zip {URL} && ls -la /tmp/s2.zip")
sh(f"mkdir -p {RAW} && unzip -q /tmp/s2.zip 's2.0.0/breps/step/*' 's2.0.0/breps/seg/*' s2.0.0/train_test.json s2.0.0/segment_names.json -d {RAW} "
   f"&& rm /tmp/s2.zip")
root = RAW / "s2.0.0"
print("segment_names.json:", (root / "segment_names.json").read_text())

limit = f" --limit {LIMIT}" if LIMIT else ""
sh(f"{ENV}/bin/python process/fusion360_to_pyg.py {root} {PROC} --num_processes {os.cpu_count()}{limit}", cwd=SRC)
sh(f"{ENV}/bin/python -c \"from datasets.fusion360 import Fusion360Dataset; "
   f"[Fusion360Dataset('{PROC}', s) for s in ('train', 'val', 'test')]\"", cwd=SRC)

# The validation split must be the one UV-Net uses (sklearn is not in the conversion env)
if not LIMIT:
    from sklearn.model_selection import train_test_split
    full_train = json.loads((root / "train_test.json").read_text())["train"]
    done = set(sum(json.loads((PROC / "split.json").read_text()).values(), []))
    ours = json.loads((PROC / "split.json").read_text())["val"]
    theirs = [n for n in train_test_split(full_train, test_size=0.2, random_state=42)[1] if n in done]
    assert ours == theirs, "validation split differs from sklearn's train_test_split"
    print(f"Validation split matches sklearn train_test_split ({len(ours)} models)")

OUT.mkdir(parents=True, exist_ok=True)
shutil.copytree(PROC / "cache", OUT / "cache")
for name in ("split.json", "failures.json"):
    if (PROC / name).exists():
        shutil.copy(PROC / name, OUT / name)
shutil.copy(root / "segment_names.json", OUT / "segment_names.json")
failures = json.loads((OUT / "failures.json").read_text()) if (OUT / "failures.json").exists() else {}
split = json.loads((OUT / "split.json").read_text())
print("\nModels per split:", {k: len(v) for k, v in split.items()}, "| failed:", len(failures))
sh(f"du -sh {OUT}/cache/*")
print(f"Done in {(time.time() - T0) / 60:.1f} min")
