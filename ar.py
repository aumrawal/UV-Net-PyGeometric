"""
Experiment runner for UV-Net autoresearch: runs a batch of train.py variants (git commits) on a
Kaggle GPU and collects their scores. Tooling, not part of the experiment: DO NOT MODIFY in the loop.

    python ar.py run <rev> [<rev> ...] [--seeds 0,1]   # push one Kaggle kernel, wait, fetch, log
    python ar.py fetch                                 # re-fetch the last batch (after an interruption)
    python ar.py status                                # state of the experiment kernel
    python ar.py local <rev> [...] [--budget 30]       # same runs on this machine (needs AR_DATA_DIR)
    python ar.py mark <rev> keep|discard               # record the decision in results.tsv
    python ar.py fake-data <dir>                       # tiny random dataset for local smoke tests

Each experiment is the train.py of one commit; prepare.py must be identical to the `harness` tag.
One kernel runs the whole batch, one experiment per GPU at a time (a Kaggle T4 x2 runs two at once).
Results go to runs/<batch>/ and are appended to results.tsv.
"""
import argparse
import base64
import json
import os
import pathlib
import subprocess
import sys
import time

ROOT = pathlib.Path(__file__).resolve().parent
CONFIG = json.loads((ROOT / "ar_config.json").read_text())
RUNS = ROOT / "runs"
RESULTS = ROOT / "results.tsv"
HEADER = "commit\tseed\tval_miou\tval_acc\tmemory_gb\tepochs\tstatus\tdescription\tbatch\n"


def git(*args):
    return subprocess.run(["git", *args], cwd=ROOT, check=True, capture_output=True, text=True).stdout


def resolve(rev):
    """Short hash, train.py source and commit subject of a revision; checks prepare.py is untouched."""
    full = git("rev-parse", "--verify", f"{rev}^{{commit}}").strip()
    if git("show", f"{full}:prepare.py") != git("show", "harness:prepare.py"):
        sys.exit(f"{rev}: prepare.py differs from the `harness` tag; experiments may only change train.py")
    git("tag", "-f", f"exp/{full[:7]}", full)   # keeps sibling commits reachable after resets
    return {"rev": full[:7], "train_py": git("show", f"{full}:train.py"), "subject": git("log", "-1", "--format=%s", full).strip()}


def kaggle(*args, check=True, timeout=120, tries=1):
    """Run the kaggle CLI; retried (with a timeout per try) because Kaggle's file server drops connections."""
    for attempt in range(1, tries + 1):
        try:
            p = subprocess.run(["kaggle", *args], capture_output=True, text=True, timeout=timeout)
            out = "\n".join(l for l in (p.stdout + p.stderr).splitlines() if "outdated" not in l)
            ok = p.returncode == 0 and "failed" not in out.lower() and "error" not in out.lower()[:200]
        except subprocess.TimeoutExpired:
            ok, out = False, f"timed out after {timeout}s"
        if ok or not check:
            return out
        print(f"  kaggle {args[0]} {args[1]}: attempt {attempt}/{tries} failed: {out.strip()[-200:]}", flush=True)
        time.sleep(20)
    sys.exit(f"kaggle {' '.join(args)} failed {tries} times")


def kernel_status():
    out = kaggle("kernels", "status", CONFIG["kernel"], check=False)
    for state in ("COMPLETE", "ERROR", "CANCEL", "RUNNING", "QUEUED"):
        if state in out.upper():
            return state
    return out.strip()


# ---------------------------------------------------------------------------------------------
# The kernel that runs on Kaggle
# ---------------------------------------------------------------------------------------------
KERNEL = r'''
"""UV-Net autoresearch batch __BATCH__, generated by ar.py. Runs each experiment's train.py, one per GPU."""
import base64, json, os, pathlib, queue, subprocess, threading, time
P = json.loads(base64.b64decode("__PAYLOAD__"))
OUT = pathlib.Path("/kaggle/working/results")
OUT.mkdir(parents=True, exist_ok=True)
T0 = time.time()
subprocess.run("pip install -q " + P["pip"], shell=True, check=True)
gpus = subprocess.run("nvidia-smi --query-gpu=name,memory.total --format=csv,noheader", shell=True,
                      capture_output=True, text=True).stdout.strip().splitlines()
print("GPUs:", gpus, flush=True)
jobs = queue.Queue()
for exp in P["experiments"]:
    jobs.put(exp)
results = []

def worker(gpu):
    while True:
        try:
            exp = jobs.get_nowait()
        except queue.Empty:
            return
        d = OUT / exp["id"]
        d.mkdir(parents=True, exist_ok=True)
        (d / "prepare.py").write_text(P["prepare_py"])
        (d / "train.py").write_text(exp["train_py"])
        env = dict(os.environ, CUDA_VISIBLE_DEVICES=str(gpu), AR_TIME_BUDGET=str(P["budget"]),
                   AR_RESULT_PATH=str(d / "result.json"), AR_SEED=str(exp["seed"]), PYTHONUNBUFFERED="1",
                   PYTHONDONTWRITEBYTECODE="1")
        t = time.time()
        print(f"[{t - T0:6.0f}s] gpu{gpu} start {exp['id']}", flush=True)
        with open(d / "run.log", "w") as log:
            try:
                rc = subprocess.run(["python", "-u", "train.py"], cwd=d, env=env, stdout=log, stderr=subprocess.STDOUT,
                                    timeout=P["budget"] + P["overhead"]).returncode
                status = "ok" if rc == 0 and (d / "result.json").exists() else "crash"
            except subprocess.TimeoutExpired:
                status = "timeout"
        r = {"id": exp["id"], "rev": exp["rev"], "seed": exp["seed"], "status": status, "gpu": gpu,
             "wall_seconds": round(time.time() - t, 1)}
        if status == "ok":
            r.update(json.loads((d / "result.json").read_text()))
        lines = (d / "run.log").read_text(errors="replace").splitlines()
        r["summary"] = [l for l in lines if ":" in l and l.split(":")[0] in
                        ("peak_vram_mb", "num_epochs", "num_steps", "num_params_M", "training_seconds")]
        r["log_tail"] = lines[-40:]
        results.append(r)
        print(f"[{time.time() - T0:6.0f}s] gpu{gpu} {status} {exp['id']} {r.get('val_miou', '')}", flush=True)

threads = [threading.Thread(target=worker, args=(g,)) for g in range(max(len(gpus), 1))]
for t in threads:
    t.start()
for t in threads:
    t.join()
for d in OUT.iterdir():
    if d.is_dir():
        (d / "prepare.py").unlink(missing_ok=True)   # identical in every run; the runner has it
W = OUT.parent
(W / "summary.json").write_text(json.dumps({"batch": P["batch"], "gpus": gpus, "results": results}, indent=1))
# Two output files instead of dozens: Kaggle's file server drops connections on many small downloads
subprocess.run(f"tar -czf {W}/results.tar.gz -C {W} results && rm -rf {OUT}", shell=True, check=True)
print(f"Batch {P['batch']} done in {(time.time() - T0) / 60:.1f} min")
'''


def build_payload(exps, budget, batch):
    return {
        "batch": batch, "budget": budget, "overhead": CONFIG["overhead_seconds"], "pip": CONFIG["pip"],
        "prepare_py": git("show", "harness:prepare.py"),
        "experiments": [{"id": f"{e['rev']}-s{s}", "rev": e["rev"], "seed": s, "train_py": e["train_py"]}
                        for e in exps for s in e["seeds"]],
    }


def cmd_run(args):
    state = kernel_status()
    if state in ("RUNNING", "QUEUED"):
        sys.exit(f"{CONFIG['kernel']} is {state}; wait for it (python ar.py fetch) before pushing a new batch")
    exps = [dict(resolve(r), seeds=args.seeds) for r in args.revs]
    batch = time.strftime("%m%d-%H%M%S")
    payload = build_payload(exps, args.budget, batch)
    folder = RUNS / batch / "kernel"
    folder.mkdir(parents=True)
    code = KERNEL.replace("__BATCH__", batch).replace("__PAYLOAD__", base64.b64encode(json.dumps(payload).encode()).decode())
    (folder / "script.py").write_text(code)
    (folder / "kernel-metadata.json").write_text(json.dumps({
        "id": CONFIG["kernel"], "title": CONFIG["kernel"].split("/")[1], "code_file": "script.py",
        "language": "python", "kernel_type": "script", "is_private": True, "enable_gpu": True,
        "enable_internet": True, "machine_shape": CONFIG["machine_shape"], "dataset_sources": [],
        "kernel_sources": [CONFIG["data_kernel"]], "competition_sources": [], "model_sources": [],
    }, indent=1))
    (RUNS / batch / "batch.json").write_text(json.dumps({"batch": batch, "budget": args.budget,
        "experiments": [{k: e[k] for k in ("rev", "subject", "seeds")} for e in exps]}, indent=1))
    (RUNS / "LAST").write_text(batch)
    n = len(payload["experiments"])
    print(f"batch {batch}: {n} runs x {args.budget}s on {CONFIG['machine_shape']}")
    print(kaggle("kernels", "push", "-p", str(folder)))
    wait_and_fetch(batch)


def wait_and_fetch(batch):
    time.sleep(30)
    t0 = time.time()
    while (state := kernel_status()) in ("RUNNING", "QUEUED"):
        print(f"  [{(time.time() - t0) / 60:5.1f} min] {state}", flush=True)
        time.sleep(60)
    print(f"kernel finished: {state}")
    fetch(batch)


def fetch(batch):
    dest = RUNS / batch / "output"
    kaggle("kernels", "output", CONFIG["kernel"], "-p", str(dest), "-o", timeout=300, tries=6)
    for tar in dest.rglob("results.tar.gz"):
        subprocess.run(["tar", "-xzf", str(tar), "-C", str(tar.parent)], check=True)
    found = list(dest.rglob("summary.json"))
    if not found:
        log = list(dest.rglob("*.log"))
        sys.exit(f"No summary.json in the kernel output (the kernel itself failed). Log: {log[0] if log else dest}")
    summary = json.loads(found[0].read_text())
    if summary["batch"] != batch:
        sys.exit(f"Kernel output is from batch {summary['batch']}, not {batch}")
    record(batch, summary)


def _mem_epochs(r):
    vals = dict(l.split(":", 1) for l in r.get("summary", []))
    mem = float(vals.get("peak_vram_mb", 0)) / 1024
    return f"{mem:.1f}", vals.get("num_epochs", "").strip() or "0"


def record(batch, summary):
    meta = {e["rev"]: e["subject"] for e in json.loads((RUNS / batch / "batch.json").read_text())["experiments"]}
    if not RESULTS.exists():
        RESULTS.write_text(HEADER)
    rows = []
    for r in sorted(summary["results"], key=lambda r: r["id"]):
        mem, epochs = _mem_epochs(r)
        status = "?" if r["status"] == "ok" else r["status"]
        rows.append(f"{r['rev']}\t{r['seed']}\t{r.get('val_miou', 0):.6f}\t{r.get('val_acc', 0):.6f}\t{mem}\t{epochs}\t"
                    f"{status}\t{meta.get(r['rev'], '')}\t{batch}\n")
    if f"\t{batch}\n" not in RESULTS.read_text():   # a re-fetch must not log the batch twice
        with open(RESULTS, "a") as f:
            f.writelines(rows)
    print(f"\nGPUs: {summary['gpus']}")
    print(f"{'run':14s} {'status':8s} {'val_miou':>9s} {'val_acc':>8s} {'mem_gb':>6s} {'epochs':>6s}  description")
    for r in sorted(summary["results"], key=lambda r: -r.get("val_miou", -1)):
        mem, epochs = _mem_epochs(r)
        print(f"{r['id']:14s} {r['status']:8s} {r.get('val_miou', 0):9.4f} {r.get('val_acc', 0):8.4f} {mem:>6s} "
              f"{epochs:>6s}  {meta.get(r['rev'], '')}")
        if r["status"] != "ok":
            print("    last log lines:\n      " + "\n      ".join(r["log_tail"][-15:]))
    print(f"\nLogs: {RUNS / batch / 'output'}")


def cmd_local(args):
    """Run revisions on this machine, sequentially, with the same contract as the kernel."""
    assert os.environ.get("AR_DATA_DIR"), "set AR_DATA_DIR to a processed dataset (python ar.py fake-data <dir>)"
    batch = "local-" + time.strftime("%m%d-%H%M%S")
    for e in (dict(resolve(r), seeds=args.seeds) for r in args.revs):
        for s in e["seeds"]:
            d = RUNS / batch / f"{e['rev']}-s{s}"
            d.mkdir(parents=True)
            (d / "prepare.py").write_text(git("show", "harness:prepare.py"))
            (d / "train.py").write_text(e["train_py"])
            env = dict(os.environ, AR_TIME_BUDGET=str(args.budget), AR_RESULT_PATH=str(d / "result.json"), AR_SEED=str(s))
            with open(d / "run.log", "w") as log:
                rc = subprocess.run([sys.executable, "-u", "train.py"], cwd=d, env=env, stdout=log, stderr=subprocess.STDOUT).returncode
            res = json.loads((d / "result.json").read_text()) if (d / "result.json").exists() else {}
            print(f"{e['rev']}-s{s}: rc {rc} val_miou {res.get('val_miou')} ({d / 'run.log'})")


def cmd_mark(args):
    lines = RESULTS.read_text().splitlines(keepends=True)
    hits = 0
    for i, l in enumerate(lines):
        cols = l.split("\t")
        if cols[0] == args.rev[:7] and cols[6] == "?":
            cols[6] = args.decision
            lines[i] = "\t".join(cols)
            hits += 1
    RESULTS.write_text("".join(lines))
    print(f"marked {hits} row(s) of {args.rev[:7]} as {args.decision}")


def cmd_fake_data(args):
    """Random graphs in the packed-cache format, for checking that train.py runs end to end."""
    import torch
    root = pathlib.Path(args.dir)
    (root / "cache").mkdir(parents=True, exist_ok=True)
    g = torch.Generator().manual_seed(0)
    split = {}
    for name, n_models in (("train", 160), ("val", 40), ("test", 40)):
        xs, es, eis, ys = [], [], [], []
        for _ in range(n_models):
            f = int(torch.randint(4, 24, (1,), generator=g))
            src = torch.randint(0, f, (2 * f,), generator=g)
            dst = (src + torch.randint(1, f, (2 * f,), generator=g)) % f
            ei = torch.cat([torch.stack([src, dst]), torch.stack([dst, src])], 1)
            xs.append(torch.randn(f, 10, 10, 7, generator=g).half())
            es.append(torch.randn(ei.size(1), 10, 6, generator=g).half())
            eis.append(ei)
            ys.append(torch.randint(0, 8, (f,), generator=g))
        names = [f"{name}_{i}" for i in range(n_models)]
        split[name] = names
        torch.save({"names": names, "names_requested": names, "x": torch.cat(xs), "edge_attr": torch.cat(es),
                    "edge_index": torch.cat(eis, 1), "y": torch.cat(ys),
                    "face_attr": torch.rand(sum(x.size(0) for x in xs), 4, generator=g),
                    "face_ptr": torch.tensor([0] + [x.size(0) for x in xs]).cumsum(0),
                    "edge_ptr": torch.tensor([0] + [e.size(0) for e in es]).cumsum(0)}, root / "cache" / f"{name}.pt")
    (root / "split.json").write_text(json.dumps(split))
    print(f"fake dataset in {root}")


def main():
    p = argparse.ArgumentParser("UV-Net autoresearch runner")
    sub = p.add_subparsers(dest="cmd", required=True)
    seeds = lambda s: [int(x) for x in s.split(",")]
    r = sub.add_parser("run"); r.add_argument("revs", nargs="+"); r.add_argument("--seeds", type=seeds, default=[0])
    r.add_argument("--budget", type=int, default=CONFIG["budget_seconds"])
    sub.add_parser("fetch"); sub.add_parser("status")
    l = sub.add_parser("local"); l.add_argument("revs", nargs="+"); l.add_argument("--seeds", type=seeds, default=[0])
    l.add_argument("--budget", type=int, default=30)
    m = sub.add_parser("mark"); m.add_argument("rev"); m.add_argument("decision", choices=("keep", "discard"))
    f = sub.add_parser("fake-data"); f.add_argument("dir")
    args = p.parse_args()
    if args.cmd == "run":
        cmd_run(args)
    elif args.cmd == "fetch":
        batch = (RUNS / "LAST").read_text().strip()
        wait_and_fetch(batch) if kernel_status() in ("RUNNING", "QUEUED") else fetch(batch)
    elif args.cmd == "status":
        print(kernel_status())
    elif args.cmd == "local":
        cmd_local(args)
    elif args.cmd == "mark":
        cmd_mark(args)
    else:
        cmd_fake_data(args)


if __name__ == "__main__":
    main()
